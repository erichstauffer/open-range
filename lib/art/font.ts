/** Anything undefined falls back to a hollow box, so a gap is visible not silent. */
const MISSING: Glyph = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####", "....."];

export function glyphFor(character: string): Glyph {
  return GLYPHS[character] ?? MISSING;
}

export function measureText(text: string, scale = 1, tracking = 0): number {
  if (text.length === 0) return 0;
  return (text.length * (ADVANCE + tracking) - (1 + tracking)) * scale;
}

export function textHeight(scale = 1): number {
  return GLYPH_H * scale;
}

/**
 * Draw `text` with its top-left at (x, y). `tracking` adds extra pixels between
 * characters before scaling, which a large title benefits from.
 */
export function drawText(
  ctx: FillTarget,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  tracking = 0,
): number {
  ctx.fillStyle = color;
  let penX = x;

  for (const character of text) {
    const glyph = glyphFor(character);
    for (let row = 0; row < GLYPH_H; row += 1) {
      const line = glyph[row];
      for (let column = 0; column < GLYPH_W; column += 1) {
        if (line[column] !== "#") continue;
        ctx.fillRect(penX + column * scale, y + row * scale, scale, scale);
      }
    }
    penX += (ADVANCE + tracking) * scale;
  }

  return penX - (1 + tracking) * scale;
}

/** Same text one pixel down-right in a darker tone first, for legibility over art. */
export function drawTextShadowed(
  ctx: FillTarget,
  text: string,
  x: number,
  y: number,
  color: string,
  shadow: string,
  scale = 1,
  tracking = 0,
): number {
  drawText(ctx, text, x + scale, y + scale, shadow, scale, tracking);
  return drawText(ctx, text, x, y, color, scale, tracking);
}
